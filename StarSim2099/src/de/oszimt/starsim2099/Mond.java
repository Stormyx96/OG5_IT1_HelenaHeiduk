package de.oszimt.starsim2099;

public class Mond extends Himmelskoerper{
	
	private String name;
	private String art;
	private String erzart;
	
	
		
	public String getName() {
		return this.name;
	}
	public void setName(String neuName) {
		this.name = neuName;
	}

	
	public String getArt() {
		return this.art;
	}
	public void setArt(String neuArt) {
		this.name = neuArt;
	}


	public String getErzart() {
		return this.erzart;
	}
	public void setErzart(String neuErzart) {
		this.name = neuErzart;
	}
	

}
